function tailwindHue(name, step) { return tailwindText.match(new RegExp(`--color-${name}-${step}: (oklch\\([^)]*\\))`))[1] }//one of tailwind's hues at one step, as its theme writes it

function flat({hexes, role, ...palette}) {//a palette that is one flat list with no names of its own, as a pixel artist's is: each color named by its place in the list, from 1, in its maker's own order, with the four drawings' crayons said by their values
	let colors = hexes.split(' ').map((hex, i) => [`${i + 1}`, ['', `#${hex}`]])
	let at = hex => { let c = colors.find(c => c[1][1] == `#${hex}`); if (!c) throw new Error(`${palette.name} has no ${hex}`); return [c[0], ''] }
	return {...palette, colors, role: Object.fromEntries(Object.entries(role).map(([drawing, hex]) => [drawing, at(hex)]))}
}

